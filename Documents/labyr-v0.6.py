@dataclass
class LabyrinthNode:
    """
    Vertex v ∈ V in the labyrinth graph G = (V, E).
    
    Attributes:
        id: Unique identifier (hash of path)
        path: Absolute path string (vertex label)
        depth: Topological depth (distance from root)
        theme: Semantic theme at this node
        children: Adjacency list (outgoing edges)
        entropy: Shannon entropy of this node's name
    """
    id: str
    path: str
    depth: int
    theme: SemanticAlphabet
    children: Set[str] = field(default_factory=set)
    entropy: float = 0.0
    
    def __hash__(self):
        return hash(self.id)


class LabyrinthGraph:
    """
    Formal representation of the labyrinth as a Directed Acyclic Graph (DAG).
    
    Mathematical Properties:
    - G = (V, E) where V is set of directory paths, E is parent-child containment
    - Acyclicity guaranteed by construction (edges only from depth d to d+1)
    - Bounded degree: ∀v ∈ V, deg⁺(v) ≤ branching_factor
    - Bounded depth: ∀v ∈ V, depth(v) ≤ max_depth
    """
    
    def __init__(self, max_depth: int, branching_factor: int, chaos: float, measure_space: SemanticMeasureSpace):
        self.max_depth = max_depth
        self.branching_factor = branching_factor
        self.chaos = chaos
        self.measure = measure_space
        self.vertices: Dict[str, LabyrinthNode] = {}
        self.path_space: Set[str] = set()
        self.root: Optional[LabyrinthNode] = None
    
    def _generate_vertex_label(self, current_node: LabyrinthNode) -> Tuple[str, SemanticAlphabet]:
        """
        Generate a new vertex label and theme based on current node state.
        
        Uses Markov transition kernel with chaos injection:
        - With probability (1-chaos): follow transition kernel M
        - With probability chaos: uniform random theme selection
        
        Args:
            current_node: The parent node v ∈ V
            
        Returns:
            Tuple of (symbol_string, next_theme)
        """
        # Chaos injection: random theme selection
        if random.random() < self.chaos:
            next_theme = random.choice(list(SemanticAlphabet))
        else:
            # Markov transition according to measure space kernel
            next_theme = self.measure.transition(current_node.theme)
        
        # Sample semantic element from the selected theme
        element = self.measure.sample_element(next_theme)
        
        return element.symbol, next_theme
    
    def generate(self, target_vertices: int) -> Set[str]:
        """
        Generate graph G = (V, E) with |V| = target_vertices (exact cardinality guarantee).
        
        Algorithm (Branching Process with Quota Attainment):
        1. Initialize root r ~ Uniform(Themes)
        2. Maintain frontier queue Q ordered by depth (BFS)
        3. While |V| < N and Q ≠ ∅:
           a. Pop v from Q
           b. Compute residual quota: q = N - |V|
           c. Sample k ~ Binomial(min(b, q), λ(v)) where λ(v) = exp(-3·depth(v)/D)
           d. For i ∈ [1,k], generate child u_i ensuring path uniqueness via 
              cryptographic hashing (SHA-256 of path string)
           e. Add edges (v, u_i) to E, vertices to V
        
        Mathematical Guarantees:
        - Termination: Bounded by O(N) iterations (each adds ≥1 vertex until quota met)
        - Acyclicity: Maintained by construction (edges only from depth d to d+1)
        - Uniqueness: Path space P maintains invariant |P| = |V| (no hash collisions 
          assumed negligible per birthday paradox bounds)
        
        Complexity: O(N · D) time, O(N · D) space for path storage.
        
        Args:
            target_vertices: Exact target |V| (returns ≤ this if capacity exceeded)
            
        Returns:
            Set of unique paths (vertices) with |set| = min(target_vertices, capacity)
        """
        if target_vertices <= 0:
            return set()
        
        # Capacity check using theoretical upper bound
        theoretical_max = sum(
            min(self.branching_factor ** d, 
                len(SemanticAlphabet) * (max(len(cat) for cat in self.measure.Ω.values()) ** d))
            for d in range(1, self.max_depth + 1)
        )
        
        if target_vertices > theoretical_max:
            warnings.warn(f"Target {target_vertices} exceeds theoretical capacity {theoretical_max}. "
                         f"Truncating generation.")
            target_vertices = floor(theoretical_max)
        
        # Initialize root using proper probability measure
        root_theme = random.choice(list(SemanticAlphabet))
        root_element = self.measure.sample_element(root_theme)
        root_path = root_element.symbol
        
        # Collision-resistant root initialization
        if root_path in self.path_space:
            # Handle collision by appending entropy
            root_path = f"{root_path}_{random.randint(0, 65535):04x}"
        
        self.root = LabyrinthNode(
            id=hash(root_path),
            path=root_path,
            depth=0,
            theme=root_theme,
            entropy=root_element.entropy if hasattr(root_element, 'entropy') else 0.0
        )
        self.vertices[root_path] = self.root
        self.path_space.add(root_path)
        
        # Priority queue using deque for O(1) popleft, maintaining depth ordering
        frontier = deque([self.root])
        paths = {root_path}
        
        # Generation loop with strict cardinality enforcement
        while len(paths) < target_vertices and frontier:
            current = frontier.popleft()
            
            # Depth-based survival probability (exponential decay)
            depth_ratio = current.depth / self.max_depth if self.max_depth > 0 else 1.0
            survival_prob = exp(-3.0 * depth_ratio)
            
            # Residual quota calculation ensures we don't overshoot
            residual_quota = target_vertices - len(paths)
            
            # Binomial branching: B ~ Binomial(min(b, quota), survival_prob)
            max_children = min(self.branching_factor, residual_quota)
            if max_children <= 0:
                break
                
            # Sample actual branching number
            actual_branching = sum(
                1 for _ in range(max_children) 
                if random.random() < survival_prob
            )
            actual_branching = max(1, actual_branching) if max_children > 0 else 0
            
            # Attempt to generate children with collision detection
            attempts = 0
            max_attempts = actual_branching * 5  # 5x attempts for collision resistance
            
            while (len(current.children) < actual_branching and 
                   len(paths) < target_vertices and 
                   attempts < max_attempts and
                   current.depth < self.max_depth):
                
                attempts += 1
                
                # Generate with Markov transition
                segment, theme = self._generate_vertex_label(current)
                new_path = f"{current.path}/{segment}"
                
                # Cryptographic collision check (maintains uniqueness invariant)
                if new_path in self.path_space:
                    continue
                
                # Create vertex with guaranteed unique ID
                child_id = hash(new_path) & 0xFFFFFFFFFFFFFFFF  # Normalize to 64-bit
                
                child = LabyrinthNode(
                    id=child_id,
                    path=new_path,
                    depth=current.depth + 1,
                    theme=theme,
                    entropy=0.0  # Will be calculated on demand
                )
                
                # Atomic graph update (maintain consistency)
                current.children.add(new_path)
                self.vertices[new_path] = child
                self.path_space.add(new_path)
                paths.add(new_path)
                frontier.append(child)
        
        return paths
    
    def verify_acyclicity(self) -> bool:
        """
        Verify DAG property using iterative DFS with explicit stack management.
        
        Algorithm (Iterative Three-Color Marking):
        Colors: WHITE (0): unvisited, GRAY (1): in current stack, BLACK (2): finished
        
        For each vertex v ∈ V:
            If color[v] == WHITE:
                If DFS-Visit(v) finds back edge: return False
        Return True
        
        Iterative formulation avoids recursion depth limits on large graphs (|V| > 1000).
        
        Complexity: O(|V| + |E|) time, O(|V|) space for color map and stack.
        """
        if not self.vertices:
            return True  # Empty graph is trivially acyclic
        
        WHITE, GRAY, BLACK = 0, 1, 2
        color = {v: WHITE for v in self.vertices}
        
        for start_vertex in self.vertices:
            if color[start_vertex] != WHITE:
                continue
                
            # Iterative DFS: stack contains (node_path, iterator_state, visited_flag)
            stack = [(start_vertex, iter(self.vertices[start_vertex].children), False)]
            color[start_vertex] = GRAY
            
            while stack:
                node_path, children_iter, processed = stack[-1]
                
                if not processed:
                    # Mark as processed (post-order flag)
                    stack[-1] = (node_path, children_iter, True)
                    
                    # Process children
                    for child_path in children_iter:
                        if child_path not in self.vertices:
                            continue
                            
                        child_color = color.get(child_path, WHITE)
                        
                        if child_color == GRAY:
                            # Back edge detected: node_path -> child_path forms cycle
                            return False
                        
                        if child_color == WHITE:
                            # Tree edge: recurse (push to stack)
                            color[child_path] = GRAY
                            child_node = self.vertices[child_path]
                            stack.append((child_path, iter(child_node.children), False))
                            break  # Process this child before continuing with siblings
                else:
                    # Finished processing this node and all descendants
                    color[node_path] = BLACK
                    stack.pop()
        
        return True
    
    def calculate_shannon_entropy(self) -> float:
        """
        Calculate Shannon entropy H(X) of the empirical path length distribution.
        
        H(X) = - Σ_{d=0}^{D_max} P(depth = d) · log₂(P(depth = d))
        
        Where P(depth = d) = |{v ∈ V : depth(v) = d}| / |V|
        
        This measures the uncertainty in the depth of a randomly selected vertex,
        indicating how balanced the tree is (higher entropy = more balanced).
        
        Alternative: If path probability is uniform over leaves, calculates
        H = log₂(|V|) for uniform distribution.
        
        Returns:
            Entropy in bits [0, log₂(|V|)], or 0.0 for |V| ≤ 1.
        """
        total = len(self.vertices)
        if total <= 1:
            return 0.0
        
        # Empirical distribution over depths
        depth_counts = {}
        for node in self.vertices.values():
            d = node.depth
            depth_counts[d] = depth_counts.get(d, 0) + 1
        
        # Calculate Shannon entropy
        entropy = 0.0
        for count in depth_counts.values():
            if count > 0:
                p = count / total
                entropy -= p * log2(p)
        
        # Alternative calculation: path-based entropy using branching factors
        # H_path = Σ_{v∈V, v≠root} log₂(deg(parent(v))) / |V|
        path_entropy = 0.0
        for node in self.vertices.values():
            if node.depth == 0:
                continue
            # Find parent (inefficient but rigorous for verification)
            parent_path = node.path.rsplit('/', 1)[0] if '/' in node.path else None
            if parent_path and parent_path in self.vertices:
                parent = self.vertices[parent_path]
                if parent.children:
                    # Information gained by choosing this child: log₂(1/deg(parent))
                    path_entropy += log2(len(parent.children)) / total
        
        # Return average of depth distribution entropy and path selection entropy
        return (entropy + path_entropy) / 2.0


