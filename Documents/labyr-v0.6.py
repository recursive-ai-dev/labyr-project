def map_keywords_to_themes(keywords: List[str]) -> List[SemanticAlphabet]:
    """
    Map user keywords to formal semantic alphabet using fuzzy logic.
    
    μ_keyword(theme) = similarity(keyword, theme) ∈ [0,1]
    """
    keyword_map = {
        "city": SemanticAlphabet.CITY, "town": SemanticAlphabet.CITY,
        "urban": SemanticAlphabet.CITY, "streets": SemanticAlphabet.CITY,
        "dungeon": SemanticAlphabet.DUNGEON, "prison": SemanticAlphabet.DUNGEON,
        "cave": SemanticAlphabet.DUNGEON, "tunnel": SemanticAlphabet.DUNGEON,
        "hell": SemanticAlphabet.HELL, "inferno": SemanticAlphabet.HELL,
        "demon": SemanticAlphabet.HELL, "abyss": SemanticAlphabet.HELL,
        "labyrinth": SemanticAlphabet.LABYRINTH, "maze": SemanticAlphabet.LABYRINTH,
        "trap": SemanticAlphabet.LABYRINTH, "corridor": SemanticAlphabet.LABYRINTH,
        "fortress": SemanticAlphabet.FORTRESS, "castle": SemanticAlphabet.FORTRESS,
        "siege": SemanticAlphabet.FORTRESS, "war": SemanticAlphabet.FORTRESS,
        "plague": SemanticAlphabet.PLAGUE, "disease": SemanticAlphabet.PLAGUE,
        "rot": SemanticAlphabet.PLAGUE, "undead": SemanticAlphabet.PLAGUE,
        "cult": SemanticAlphabet.CULT, "ritual": SemanticAlphabet.CULT,
        "sacrifice": SemanticAlphabet.CULT, "occult": SemanticAlphabet.CULT,
        "graveyard": SemanticAlphabet.GRAVEYARD, "cemetery": SemanticAlphabet.GRAVEYARD,
        "tomb": SemanticAlphabet.GRAVEYARD, "burial": SemanticAlphabet.GRAVEYARD,
    }
    
    themes = set()
    for kw in keywords:
        kw_lower = kw.lower()
        if kw_lower in keyword_map:
            themes.add(keyword_map[kw_lower])
        else:
            # Partial matching
            for key, theme in keyword_map.items():
                if key in kw_lower or kw_lower in key:
                    themes.add(theme)
                    break
    
    # Default to full alphabet if no matches
    if not themes:
        themes = set(SemanticAlphabet)
    
    return list(themes)


