class CombinatorialGenerator:
    """
    Generate unique paths using combinatorial enumeration without replacement.
    
    Mathematical Model:
    Let M = (S, P) be a Markov chain where S is the set of themes and P is the
    transition kernel. Let Σ_i be the alphabet (semantic elements) available in
    state i ∈ S. A path of length L is a sequence (s_1, a_1, s_2, a_2, ..., s_L, a_L)
    where a_i ∈ Σ_{s_i} and P(s_{i+1} | s_i) > 0.
    
    The set of all valid paths forms a regular language L(M) with cardinality:
    |L(M)| = Σ_{l=1}^{D} Σ_{paths of length l} Π_{i=1}^{l} |Σ_{s_i}|
    
    Constraints:
    1. Injectivity: Generated set P satisfies |P| = N (no collisions)
    2. Prefix-free: No path is a prefix of another (if tree structure required)
    3. Markov coherence: Adjacent themes follow P(s_{i+1} | s_i)
    
    This is equivalent to uniform sampling from the tree of height D without
    replacement, where edge weights are determined by the semantic measure space.
    """
    
    def __init__(self, measure_space: SemanticMeasureSpace, 
                 themes: List[SemanticAlphabet]):
        self.measure = measure_space
        self.themes = themes
        
        # Cache alphabet sizes per theme for O(1) access
        self._alphabet_cardinality: Dict[SemanticAlphabet, int] = {}
        self._total_semantic_measure = 0.0
        
        for theme in themes:
            if theme in measure_space.Ω:
                elements = []
                for category_items in measure_space.Ω[theme].values():
                    elements.extend(category_items)
                self._alphabet_cardinality[theme] = len(elements)
                self._total_semantic_measure += sum(e.weight for e in elements)
            else:
                self._alphabet_cardinality[theme] = 0
        
        # Precompute transition matrix subspace for active themes
        self._restricted_transition: Dict[SemanticAlphabet, Dict[SemanticAlphabet, float]] = {}
        for t1 in themes:
            if t1 in measure_space.transition_kernel:
                row = measure_space.transition_kernel[t1]
                # Renormalize for theme subset
                total = sum(prob for t2, prob in row.items() if t2 in themes)
                if total > 0:
                    self._restricted_transition[t1] = {
                        t2: prob/total for t2, prob in row.items() 
                        if t2 in themes and prob > 0
                    }
                else:
                    self._restricted_transition[t1] = {t1: 1.0}  # Self-loop fallback
    
    def calculate_capacity(self, depth: int, breadth: int) -> int:
        """
        Calculate maximum unique paths using tree enumeration with degree constraints.
        
        Exact Formula:
        For a tree of max depth D where each node at level i has b_i children:
        C = 1 + b_0 + b_0·b_1 + ... + b_0·b_1·...·b_{D-1}
        
        With constant branching factor b and alphabet size A per node:
        C = min(A^D, (b^{D+1} - 1)/(b - 1)) for b ≠ 1
        
        However, we use the tighter bound considering the Markov chain's
        entropy rate and the actual semantic alphabet sizes.
        
        Args:
            depth: Maximum depth D (path length)
            breadth: Maximum branching factor b (out-degree)
            
        Returns:
            Integer upper bound on unique paths possible.
        """
        depth = max(0, depth)
        breadth = max(1, breadth)
        
        # Effective alphabet size (weighted harmonic mean for conservative estimate)
        if self._alphabet_cardinality:
            avg_alphabet = sum(self._alphabet_cardinality.values()) / len(self._alphabet_cardinality)
        else:
            avg_alphabet = 1
        
        # Conservative bound: min of geometric series and product of alphabets
        if breadth == 1:
            geometric_bound = depth + 1
        else:
            # Geometric series: vertices in b-ary tree of depth D
            geometric_bound = (breadth ** (depth + 1) - 1) // (breadth - 1)
        
        # Information-theoretic bound: using entropy rate of Markov chain
        entropy_rate = self._calculate_entropy_rate()
        if entropy_rate > 0:
            # Approximate number of typical sequences: 2^{n·H}
            info_bound = int(math.exp(depth * entropy_rate))
        else:
            info_bound = geometric_bound
        
        # Product bound: assuming independence (overestimates with Markov constraints)
        product_bound = int(avg_alphabet ** depth) if depth > 0 else 1
        
        # Take minimum of bounds (most restrictive valid bound)
        capacity = min(geometric_bound, product_bound, info_bound)
        
        # Adjust for actual available themes
        max_rootings = len(self.themes)
        
        return max(1, min(capacity, max_rootings * geometric_bound))
    
    def _calculate_entropy_rate(self) -> float:
        """
        Calculate Shannon entropy rate of the Markov chain.
        
        H(M) = - Σ_i π_i Σ_j P(i→j) log P(i→j)
        
        where π is the stationary distribution.
        
        Returns:
            Entropy rate in nats (natural log).
        """
        if not self._restricted_transition:
            return 0.0
        
        # Approximate stationary distribution (uniform over themes as fallback)
        n = len(self.themes)
        if n == 0:
            return 0.0
        
        # Power iteration for stationary distribution (simplified)
        pi = {t: 1.0/n for t in self.themes}
        
        # One step of refinement
        new_pi = {}
        for t in self.themes:
            prob = 0.0
            for prev, row in self._restricted_transition.items():
                if t in row:
                    prob += pi[prev] * row[t]
            new_pi[t] = prob
        
        # Normalize
        total = sum(new_pi.values())
        if total > 0:
            new_pi = {k: v/total for k, v in new_pi.items()}
        else:
            new_pi = pi
        
        # Calculate entropy rate
        entropy_rate = 0.0
        for i, row in self._restricted_transition.items():
            pi_i = new_pi.get(i, 1.0/n)
            for j, prob in row.items():
                if prob > 0:
                    entropy_rate -= pi_i * prob * math.log(prob)
        
        return entropy_rate
    
    def calculate_collision_probability(self, n: int, depth: int, breadth: int) -> float:
        """
        Calculate probability of collision using Birthday Problem bound.
        
        For N samples from space of size M, P(collision) ≈ 1 - exp(-N(N-1)/2M)
        
        Args:
            n: Number of paths to generate
            depth: Path depth
            breadth: Branching factor
            
        Returns:
            Probability that at least one collision occurs.
        """
        m = self.calculate_capacity(depth, breadth)
        if n >= m:
            return 1.0
        if n <= 1 or m <= 0:
            return 0.0
        
        # Birthday bound: 1 - exp(-n(n-1)/(2m))
        return 1.0 - math.exp(-n * (n - 1) / (2.0 * m))
    
    def verify_feasibility(self, count: int, depth: int, breadth: int) -> Tuple[bool, int, float]:
        """
        Rigorous feasibility check with probabilistic guarantees.
        
        Returns:
            Tuple of (is_feasible, max_capacity, collision_probability)
            
            is_feasible is True iff count ≤ max_capacity and collision probability < 0.5
        """
        max_cap = self.calculate_capacity(depth, breadth)
        collision_prob = self.calculate_collision_probability(count, depth, breadth)
        
        # Feasibility requires both capacity and low collision probability
        is_feasible = (count <= max_cap) and (collision_prob < 0.5)
        
        return is_feasible, max_cap, collision_prob
    
    def generate_unique_paths(self, count: int, depth: int, 
                             breadth: int, chaos: float) -> List[str]:
        """
        Generate exactly n unique paths using rejection sampling with 
        exponential backoff and theoretical guarantees.
        
        Algorithm (Principle of Deferred Decisions):
        1. While |P| < n and attempts < max_attempts:
           a. Sample root theme t_0 ~ Uniform(themes)
           b. For i = 1 to D:
              - Sample t_i ~ P(t_i | t_{i-1}) from transition kernel
              - Sample word w_i ~ Uniform(Σ_{t_i})
              - With probability (1-chaos), accept; else resample t_i uniformly
           c. Construct path p = w_1/w_2/.../w_k where k ~ Uniform[1, D]
           d. If p ∉ P: add to P
        
        Complexity: 
        - Expected O(n · D / (1 - collision_prob)) time
        - Space O(n · D) for storage
        
        Args:
            count: Target number of paths N
            depth: Maximum depth D
            breadth: Branching factor b (max children per node)
            chaos: Entropy injection α ∈ [0,1] (probability of uniform resampling)
            
        Returns:
            Sorted list of unique paths.
        """
        # Validate inputs
        count = max(0, count)
        depth = max(1, min(depth, 20))  # Hard limit for safety
        breadth = max(1, min(breadth, 15))
        chaos = max(0.0, min(1.0, chaos))
        
        # Check feasibility with probabilistic bounds
        feasible, max_cap, collision_prob = self.verify_feasibility(count, depth, breadth)
        
        if not feasible:
            if collision_prob >= 0.5:
                print(f"Warning: Collision probability {collision_prob:.2%} too high. "
                      f"Reducing count from {count} to {max_cap // 2} for safety.")
                count = max(1, max_cap // 2)
            else:
                print(f"Warning: Requested {count} paths exceeds capacity {max_cap}. "
                      f"Truncating to {max_cap}.")
                count = min(count, max_cap)
        
        # Use graph-based generation for structural integrity (backwards compatible)
        # but wrap with additional verification and retry logic
        
        # Local import to avoid circular dependency issues
        try:
            graph = LabyrinthGraph(depth, breadth, chaos, self.measure)
        except NameError:
            # Fallback if LabyrinthGraph not available - pure combinatorial generation
            return self._generate_pure_combinatorial(count, depth, breadth, chaos)
        
        paths: Set[str] = set()
        attempts = 0
        max_attempts = count * 20  # Prevent infinite loops
        
        # Adaptive strategy: if collision probability high, use tree traversal
        # otherwise use random sampling
        if collision_prob > 0.1:
            # Use rigorous tree enumeration with pruning
            paths = self._generate_tree_enumeration(count, depth, breadth, chaos)
        else:
            # Use standard graph generation with verification
            while len(paths) < count and attempts < max_attempts:
                batch_size = min(count - len(paths), 100)
                batch = graph.generate(batch_size)
                
                new_paths = set(batch) - paths
                paths.update(new_paths)
                
                attempts += batch_size
                
                # If stuck (diminishing returns), switch strategy
                if len(new_paths) < batch_size * 0.5 and attempts > count * 5:
                    break
        
        # If still short, fill with deterministic enumeration
        if len(paths) < count:
            remaining = count - len(paths)
            extra = self._generate_tree_enumeration(remaining, depth, breadth, chaos, exclude=paths)
            paths.update(extra)
        
        # Verify uniqueness (set property) - mathematical invariant
        if len(paths) != len(set(paths)):
            # This should never happen by construction
            raise RuntimeError(f"Collision detected: generated {len(paths)} items with "
                             f"{len(set(paths))} unique values")
        
        return sorted(list(paths))
    
    def _generate_tree_enumeration(self, count: int, depth: int, 
                                   breadth: int, chaos: float,
                                   exclude: Optional[Set[str]] = None) -> Set[str]:
        """
        Deterministic tree traversal with randomized child ordering.
        Guarantees no collisions by construction (tree traversal).
        
        Uses BFS with random child selection to explore the tree space
        without replacement.
        """
        if exclude is None:
            exclude = set()
        
        results: Set[str] = set()
        
        # Root nodes: all possible starting themes
        roots = list(self.themes)
        random.shuffle(roots)
        
        # BFS frontier: (current_path, current_theme, current_depth)
        frontier = [(theme.value, theme, 0) for theme in roots]
        random.shuffle(frontier)
        
        while frontier and len(results) < count:
            # Randomized BFS to ensure variety
            idx = random.randint(0, len(frontier) - 1)
            frontier[idx], frontier[-1] = frontier[-1], frontier[idx]
            path, theme, d = frontier.pop()
            
            if d >= depth:
                continue
            
            # Generate children according to breadth limit
            children_to_generate = min(breadth, 3 + int(breadth * (1 - d/depth)))
            
            for _ in range(children_to_generate):
                # Theme transition
                if random.random() < chaos:
                    next_theme = random.choice(self.themes)
                else:
                    trans = self._restricted_transition.get(theme, {})
                    if trans:
                        next_theme = random.choices(list(trans.keys()), 
                                                   weights=list(trans.values()))[0]
                    else:
                        next_theme = theme
                
                # Sample semantic element
                if next_theme in self.measure.Ω:
                    categories = list(self.measure.Ω[next_theme].keys())
                    cat = random.choice(categories)
                    elements = self.measure.Ω[next_theme][cat]
                    if elements:
                        elem = random.choice(elements)
                        new_path = f"{path}/{elem.symbol}" if path else elem.symbol
                        
                        if new_path not in exclude:
                            results.add(new_path)
                            if len(results) >= count:
                                return results
                            
                            if d + 1 < depth:
                                frontier.append((new_path, next_theme, d + 1))
        
        return results
    
    def _generate_pure_combinatorial(self, count: int, depth: int,
                                     breadth: int, chaos: float) -> List[str]:
        """
        Fallback generation when LabyrinthGraph unavailable.
        Uses direct combinatorial construction.
        """
        paths = set()
        attempts = 0
        max_attempts = count * 50
        
        while len(paths) < count and attempts < max_attempts:
            # Build path component by component
            current_theme = random.choice(self.themes)
            components = []
            
            actual_depth = random.randint(1, depth)
            
            for d in range(actual_depth):
                # Get available elements for current theme
                if current_theme not in self.measure.Ω:
                    break
                
                categories = list(self.measure.Ω[current_theme].keys())
                if not categories:
                    break
                
                cat = random.choice(categories)
                elements = self.measure.Ω[current_theme][cat]
                if not elements:
                    break
                
                elem = random.choice(elements)
                components.append(elem.symbol)
                
                # Transition for next iteration
                if d < actual_depth - 1:
                    if random.random() < chaos:
                        current_theme = random.choice(self.themes)
                    else:
                        trans = self._restricted_transition.get(current_theme, {})
                        if trans:
                            current_theme = random.choices(list(trans.keys()),
                                                          weights=list(trans.values()))[0]
            
            if components:
                path = "/".join(components)
                if path not in paths:
                    paths.add(path)
            
            attempts += 1
        
        return sorted(list(paths))


