    def _construct_transition_kernel(self):
        """
        Construct stochastic matrix M where M[i,j] = P(Theme_j | Theme_i)
        
        Properties:
        1. ∀i, Σ_j M[i,j] = 1 (row sums to 1)
        2. M[i,j] ≥ 0 (non-negative)
        3. High probability for self-transitions (thematic coherence)
        4. Non-zero probability for related themes (semantic similarity)
        
        We define this as a Markov chain on the theme space.
        """
        themes = list(SemanticAlphabet)
        n = len(themes)
        
        # Define semantic similarity matrix (symmetric)
        similarity = {
            (SemanticAlphabet.CITY, SemanticAlphabet.FORTRESS): 0.3,
            (SemanticAlphabet.CITY, SemanticAlphabet.PLAGUE): 0.4,
            (SemanticAlphabet.DUNGEON, SemanticAlphabet.HELL): 0.4,
            (SemanticAlphabet.DUNGEON, SemanticAlphabet.FORTRESS): 0.3,
            (SemanticAlphabet.DUNGEON, SemanticAlphabet.CULT): 0.2,
            (SemanticAlphabet.HELL, SemanticAlphabet.CULT): 0.3,
            (SemanticAlphabet.LABYRINTH, SemanticAlphabet.DUNGEON): 0.3,
            (SemanticAlphabet.FORTRESS, SemanticAlphabet.GRAVEYARD): 0.2,
            (SemanticAlphabet.PLAGUE, SemanticAlphabet.GRAVEYARD): 0.5,
            (SemanticAlphabet.CULT, SemanticAlphabet.GRAVEYARD): 0.3,
        }
        
        # Make symmetric
        similarity.update({(k[1], k[0]): v for k, v in similarity.items()})
        
        # Construct transition kernel
        for i in themes:
            row = {}
            total = 0.0
            
            for j in themes:
                if i == j:
                    # Self-transition (thematic coherence)
                    prob = 0.6
                elif (i, j) in similarity:
                    prob = similarity[(i, j)]
                else:
                    # Baseline transition
                    prob = 0.05
                
                row[j] = prob
                total += prob
            
            # Normalize to ensure Σ_j M[i,j] = 1
            self.transition_kernel[i] = {k: v/total for k, v in row.items()}
    
    def _validate_measure(self):
        """Verify measure axioms: normalization and non-negativity"""
        for theme, categories in self.Ω.items():
            for cat, elements in categories.items():
                total_prob = sum(e.weight for e in elements)
                # Allow small floating point error
                assert abs(total_prob - 1.0) < 1e-6 or total_prob == 0, \
                    f"Measure violation in {theme}.{cat}: {total_prob}"
    
    def sample_element(self, theme: SemanticAlphabet, 
                      category: Optional[str] = None) -> SemanticElement:
        """
        Sample ω ∈ Ω according to probability measure P.
        
        Uses inverse transform sampling:
        1. Generate u ~ Uniform(0,1)
        2. Return smallest x such that CDF(x) ≥ u
        """
        if theme not in self.Ω:
            raise ValueError(f"Invalid theme: {theme}")
        
        categories = self.Ω[theme]
        
        if category and category in categories:
            elements = categories[category]
        else:
            # Pool all elements from theme
            elements = [e for cats in categories.values() for e in cats]
        
        # Weighted random selection
        weights = [e.weight for e in elements]
        total = sum(weights)
        if total == 0:
            return random.choice(elements)
        
        r = random.uniform(0, total)
        cumulative = 0.0
        for element in elements:
            cumulative += element.weight
            if r <= cumulative:
                return element
        
        return elements[-1]
    
    def transition(self, current_theme: SemanticAlphabet) -> SemanticAlphabet:
        """
        Markov transition: sample next theme from transition kernel.
        """
        row = self.transition_kernel[current_theme]
        themes = list(row.keys())
        weights = list(row.values())
        return random.choices(themes, weights=weights, k=1)[0]


