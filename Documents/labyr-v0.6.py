@dataclass(frozen=True)
class SemanticElement:
    """
    Atomic element ω ∈ Ω of the semantic probability space.
    
    Attributes:
        symbol: The string representation (formally, a point in the name space)
        theme: The measurable set A ∈ F containing this element
        weight: Probability mass P({ω}) for weighted selection
        entropy: Information content -log₂(P({ω})) in bits
    """
    symbol: str
    theme: SemanticAlphabet
    category: str
    weight: float = 1.0
    
    def __post_init__(self):
        # Normalize weight to valid probability mass
        object.__setattr__(self, 'weight', max(0.0, min(1.0, self.weight)))
        object.__setattr__(self, 'entropy', -log2(self.weight) if self.weight > 0 else float('inf'))


