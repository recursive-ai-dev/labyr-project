class TopologicalConstraint:
    """
    Formal constraints on the labyrinth graph G = (V, E)
    
    Let G be a directed acyclic graph (DAG) representing the folder hierarchy.
    We enforce:
    1. No cycles: ∃v ∈ V, no non-empty path p: v → ... → v
    2. Bounded in-degree: ∀v ∈ V, deg⁻(v) ≤ MAX_IN_DEGREE
    3. Bounded depth: ∀v ∈ V, depth(v) ≤ MAX_DEPTH
    4. Connectivity: G is a rooted forest (disconnected components allowed)
    """
    MAX_DEPTH: int = 20
    MAX_IN_DEGREE: int = 5
    MAX_BRANCHING_FACTOR: int = 15
    
    # Entropy threshold for thematic coherence (in bits)
    MIN_THEMATIC_ENTROPY: float = 2.0


